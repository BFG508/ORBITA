def _load_metrics_csv(path):
    """
    Loads a metrics CSV file into a pandas DataFrame checking data/metrics/ first.
    """
    filename = os.path.basename(path)
    candidates = [
        os.path.join("data", "metrics", filename),
        os.path.join("data", filename),
        path,
    ]
    for p in candidates:
        if os.path.exists(p):
            return pd.read_csv(p)
    print(f" [warn] Metrics file not found: {path}")
    return None


def _find_benchmark_csv(mode, arch, data_dir="data", use_finetuned=True):
    """
    Resolves benchmark CSV paths across ablation_global and ablation_resnet folders.
    """
    if use_finetuned:
        filenames = [
            f"benchmark_{mode}_{arch}_finetuned.csv",
            f"benchmark_{mode}_{arch}.csv",
        ]
    else:
        filenames = [
            f"benchmark_{mode}_{arch}_base.csv",
            f"benchmark_{mode}_{arch}.csv",
        ]
    for filename in filenames:
        candidates = [
            os.path.join(data_dir, "benchmarks", "ablation_global", filename),
            os.path.join(data_dir, "benchmarks", "ablation_resnet", filename),
            os.path.join(data_dir, "benchmarks", "ablation", filename),
            os.path.join(data_dir, filename),
        ]
        for p in candidates:
            if os.path.exists(p):
                return p
    return None


def _extract_architecture(project_name):
    """
    Extracts the architecture token from CodeCarbon project names.

    Examples:
        train_resnet_orbita_dataset_...
        benchmark_time_domain_lstm
        benchmark_space_domain_tree
    """
    tokens = str(project_name).lower().split("_")
    for architecture in ARCH_ORDER:
        if architecture in tokens:
            return architecture
    return "unknown"


def _infer_emission_phase(project_name):
    """
    Classifies direct CodeCarbon rows by measured run phase.
    """
    project_name = str(project_name).lower()
    if project_name.startswith("train_"):
        return "train"
    if project_name.startswith("benchmark_time_domain_"):
        return "benchmark_time_domain"
    if project_name.startswith("benchmark_space_domain_"):
        return "benchmark_space_domain"
    return "unknown"


