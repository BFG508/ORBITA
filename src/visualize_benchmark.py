"""
Script: visualize_benchmark.py

Description:
    Advanced telemetry and analytics visualization suite for the ORBITA framework.
    
    This script parses the CSV outputs generated by the benchmark suite 
    and produces publication-quality, high-density figures. It features 
    absolute magnitude error analysis and uses a custom 'plasma' color 
    palette to maintain visual consistency with ESTHER.
    
    All figures are exported in both .png (raster) and .svg (vector) formats
    to ensure lossless scaling in LaTeX documents. Optimized for massive datasets.
"""

import os
import pandas as pd
import numpy as np
import matplotlib as mpl
import matplotlib.pyplot as plt
import seaborn as sns

from physics.oracle import R_EQ

# =============================================================================
# GLOBAL COLOR PALETTE (From ESTHER 'plasma' colormap)
# =============================================================================
COLOR_R = (0.20, 0.02, 0.40)  # Dark Purple (Radial)
COLOR_I = (0.56, 0.07, 0.65)  # Magenta/Purple (In-Track)
COLOR_C = (0.95, 0.52, 0.27)  # Orange (Cross-Track)


def configure_style():
    """
    Configures Matplotlib and Seaborn for high-quality figures,
    strictly matching the classic LaTeX 'Computer Modern' serif font 
    used in ESTHER.
    """
    sns.set_theme(style="ticks")
    
    # Set font family
    mpl.rcParams['font.family'] = 'serif'
    mpl.rcParams['font.serif'] = ['Computer Modern Roman', 'Times New Roman']
    mpl.rcParams['mathtext.fontset'] = 'cm'
    
    # Sizes and PDF export settings
    mpl.rcParams['axes.titlesize'] = 14
    mpl.rcParams['axes.labelsize'] = 12
    mpl.rcParams['xtick.labelsize'] = 11
    mpl.rcParams['ytick.labelsize'] = 11
    mpl.rcParams['legend.fontsize'] = 11
    mpl.rcParams['figure.titlesize'] = 16
    mpl.rcParams['figure.dpi'] = 300
    mpl.rcParams['pdf.fonttype'] = 42
    mpl.rcParams['ps.fonttype'] = 42


def save_format(output_path, description, bbox_inches='tight'):
    """
    Helper function to save the current figure in both PNG and SVG formats, 
    and output a single clean, descriptive console notification.
    
    Args:
        output_path (str): Original target path (expected to end in .png).
        description (str): Human-readable description of the saved figure.
        bbox_inches (str): Bounding box specification for Matplotlib (default: 'tight').
    """
    plt.savefig(output_path, dpi=300, bbox_inches=bbox_inches)
    vector_path = os.path.splitext(output_path)[0] + ".svg"
    plt.savefig(vector_path, bbox_inches=bbox_inches)
    
    print(f" [saved] {description}")


def plot_time_domain(csv_path="data/benchmark_time_domain.csv", output_filename="figures/plot_time_domain.png"):
    """
    Generates a stacked subplot figure showing the absolute secular error 
    accumulation over time for each individual RIC component.
    """
    if not os.path.exists(csv_path):
        print(f" [error] Time-domain data not found at: {csv_path}")
        return

    df = pd.read_csv(csv_path)
    df['Time_hours'] = df['Time_s'] / 3600.0
    
    abs_radial = np.abs(df['Radial_m'])
    abs_intrack = np.abs(df['InTrack_m'])
    abs_crosstrack = np.abs(df['CrossTrack_m'])

    _, axes = plt.subplots(3, 1, figsize=(10, 10), sharex=True)
    
    axes[0].plot(df['Time_hours'], abs_radial, color=COLOR_R, linewidth=2)
    axes[0].set_ylabel("Radial Error [m]")
    axes[0].set_ylim(bottom=0)
    axes[0].set_title("ORBITA Hybrid Propagation: Absolute Secular Error Accumulation", pad=15, fontweight='bold')
    
    axes[1].plot(df['Time_hours'], abs_intrack, color=COLOR_I, linewidth=2)
    axes[1].set_ylabel("In-Track Error [m]")
    axes[1].set_ylim(bottom=0)
    
    axes[2].plot(df['Time_hours'], abs_crosstrack, color=COLOR_C, linewidth=2)
    axes[2].set_ylabel("Cross-Track Error [m]")
    axes[2].set_xlabel("Time of Flight [h]", fontsize=12, fontweight='bold')
    axes[0].set_xlim(left=15.0/60)
    axes[0].set_xlim(right=df['Time_hours'].max())
    axes[2].set_ylim(bottom=0)
    
    for ax in axes:
        ax.grid(True, linestyle='-', alpha=0.6)
        
    plt.tight_layout()
    save_format(output_filename, "Time-Domain Secular Error Accumulation")
    plt.close()


def plot_space_domain_distributions(df, output_prefix):
    """
    Generates statistical distribution panels using the absolute magnitude 
    of the errors. Consolidates the statistical markers into a single global legend.
    """
    fig, axes = plt.subplots(1, 3, figsize=(18, 5))
    components = [
        ('Abs_Radial_m', 'Absolute Radial Error', COLOR_R),
        ('Abs_InTrack_m', 'Absolute In-Track Error', COLOR_I),
        ('Abs_CrossTrack_m', 'Absolute Cross-Track Error', COLOR_C)
    ]
    
    for i, (ax, (col, title, color)) in enumerate(zip(axes, components)):
        sns.histplot(df[col], kde=True, ax=ax, color=color, stat='density', alpha=0.5)
        
        mean_val = df[col].mean()
        p95_val = np.percentile(df[col], 95)
        
        ax.axvline(mean_val, color='black', linestyle='-', linewidth=1.5, label='Mean')
        ax.axvline(p95_val, color='gray', linestyle='--', linewidth=1.5, label=r'95$^{\mathrm{th}}$ Percentile')
        
        ax.set_title(title, fontsize=12, fontweight='bold')
        ax.set_xlabel("Absolute Error [m]")
        ax.set_xlim(left=0)

        ax.grid(True, linestyle='-', alpha=0.6)
        
        if i > 0:
            ax.set_ylabel('')
            
    handles, labels = axes[0].get_legend_handles_labels()
    fig.legend(handles, labels, loc='upper center', bbox_to_anchor=(0.515, 1), ncol=2, fontsize=11)
    
    plt.suptitle("MoE Generalization: Absolute RIC Error Distributions", x=0.516, y=1.05, fontweight='bold')
    plt.tight_layout()
    
    hist_output = f"{output_prefix}_histograms.png"
    save_format(hist_output, "Absolute RIC Error Distributions (Histograms)")
    plt.close()


def plot_space_domain_scatter_trends(df, output_prefix, max_samples=5000):
    """
    Generates scatter plots correlating the absolute radial error with orbital parameters.
    Uses random subsampling and rasterized scatters to drastically reduce 
    LOWESS calculation time and SVG export bloat.
    """
    if len(df) > max_samples:
        df_plot = df.sample(n=max_samples, random_state=42)
    else:
        df_plot = df

    fig, axes = plt.subplots(1, 3, figsize=(18, 5))
    
    sns.regplot(
        x=df_plot['SMA_km'] - R_EQ/1e3, y=df_plot['Abs_Radial_m'], ax=axes[0], 
        scatter_kws={'alpha': 0.3, 'color': COLOR_R, 'rasterized': True}, 
        line_kws={'color': 'black', 'linewidth': 2}, lowess=True
    )
    axes[0].set_title("Absolute Radial Error vs. Altitude", fontsize=12, fontweight='bold')
    axes[0].set_xlabel("Semi-Major Axis [km]")
    axes[0].set_ylabel("Absolute Radial Error [m]")
    axes[0].set_ylim(bottom=0)
    axes[0].set_xlim(left=(df_plot['SMA_km'] - R_EQ/1e3).min())
    axes[0].set_xlim(right=(df_plot['SMA_km'] - R_EQ/1e3).max())
    
    sns.regplot(
        x=df_plot['ECC'], y=df_plot['Abs_Radial_m'], ax=axes[1], 
        scatter_kws={'alpha': 0.3, 'color': COLOR_R, 'rasterized': True}, 
        line_kws={'color': 'black', 'linewidth': 2}, lowess=True
    )
    axes[1].set_title("Absolute Radial Error vs. Eccentricity", fontsize=12, fontweight='bold')
    axes[1].set_xlabel("Eccentricity [-]")
    axes[1].set_ylim(bottom=0)
    axes[1].set_xlim(left=df_plot['ECC'].min())
    axes[1].set_xlim(right=df_plot['ECC'].max())
    
    sns.regplot(
        x=np.rad2deg(df_plot['INC_rad']), y=df_plot['Abs_Radial_m'], ax=axes[2], 
        scatter_kws={'alpha': 0.3, 'color': COLOR_R, 'rasterized': True}, 
        line_kws={'color': 'black', 'linewidth': 2}, lowess=True
    )
    axes[2].set_title("Absolute Radial Error vs. Inclination", fontsize=12, fontweight='bold')
    axes[2].set_xlabel("Inclination [deg]")
    axes[2].set_ylim(bottom=0)
    axes[2].set_xlim(left=(np.rad2deg(df_plot['INC_rad'])).min())
    axes[2].set_xlim(right=(np.rad2deg(df_plot['INC_rad'])).max())

    for i, ax in enumerate(axes):
        ax.grid(True, linestyle='-', alpha=0.6)
        if i > 0:
            ax.set_ylabel('')
    
    plt.suptitle("MoE Generalization: Radial Boundary Condition Analysis", x=0.514, fontweight='bold')
    plt.tight_layout()
    
    scatter_output = f"{output_prefix}_scatter.png"
    save_format(scatter_output, "Radial Boundary Condition Analysis (Scatter/LOWESS)")
    plt.close()


def plot_domain_heatmap(df, output_filename="figures/plot_space_domain_heatmap.png"):
    """
    Generates a clean Hexbin Heatmap using the ESTHER 'plasma' colormap 
    to map the topological error distribution.
    """
    _, ax = plt.subplots(figsize=(10, 8))
    
    hb = ax.hexbin(
        df['SMA_km'] - R_EQ/1e3, df['ECC'], C=df['Abs_InTrack_m'], 
        reduce_C_function=np.mean, gridsize=30, 
        cmap='plasma', edgecolors='white', linewidths=0.2, rasterized=True
    )
    
    cbar = plt.colorbar(hb, ax=ax)
    cbar.set_label('Mean Absolute In-Track Error [m]', labelpad=20, fontsize=12.5, fontweight='bold')
    
    ax.set_xlabel("Semi-Major Axis [km]", fontsize=12)
    ax.set_ylabel("Eccentricity [-]", fontsize=12)
    ax.set_title("MoE Topological Absolute Error Density Map", pad=15, fontweight='bold')
    ax.grid(True, linestyle='-', alpha=0.6)
    
    plt.tight_layout()
    save_format(output_filename, "Topological Error Density Map (Heatmap)")
    plt.close()


def plot_regime_violin(df, output_filename="figures/plot_space_domain_violin.png"):
    """
    Categorizes the dataset into LEO regimes and plots a Violin distribution 
    using a custom gradient extracted from the 'plasma' colormap.
    """
    df['Altitude_km'] = df['SMA_km'] - R_EQ/1e3
    bins = [0, 600, 1200, 2000]
    labels = ['Low LEO (< 600km)', 'Medium LEO (600-1200km)', 'High LEO (> 1200km)']
    df['Regime'] = pd.cut(df['Altitude_km'], bins=bins, labels=labels)
    
    df_clean = df.dropna(subset=['Regime']).copy()
    
    plt.figure(figsize=(10, 6))
    
    plasma_gradient = [COLOR_R, COLOR_I, COLOR_C]
    
    sns.violinplot(
        data=df_clean, x='Regime', y='Abs_Radial_m', hue='Regime',
        palette=plasma_gradient, inner="quartile", density_norm="width", 
        rasterized=True, legend=False, dodge=False
    )
    
    plt.title("Absolute Radial Error Distribution Across LEO Regimes", pad=15, fontweight='bold')
    plt.xlabel("Orbital Regime", labelpad=10, fontweight='bold')
    plt.ylabel("Absolute Radial Error [m]")
    plt.grid(True, linestyle='-', alpha=0.6)
    
    plt.tight_layout()
    save_format(output_filename, "Radial Error Distribution Across LEO Regimes (Violin)")
    plt.close()


def plot_error_cdf(df, output_filename="figures/plot_space_domain_cdf.png"):
    """
    Generates a Cumulative Distribution Function (CDF) plot for absolute RIC errors.
    """
    plt.figure(figsize=(9, 6))
    
    sns.ecdfplot(df['Abs_Radial_m'], label='Radial Error', color=COLOR_R, linewidth=2)
    sns.ecdfplot(df['Abs_InTrack_m'], label='In-Track Error', color=COLOR_I, linewidth=2)
    sns.ecdfplot(df['Abs_CrossTrack_m'], label='Cross-Track Error', color=COLOR_C, linewidth=2)
    
    plt.axhline(0.95, color='gray', linestyle='--', linewidth=1)
    plt.text(0.825, 0.92, '95% Confidence Bound', transform=plt.gca().transAxes, fontsize=10, color='gray')
    
    plt.title("Cumulative Distribution Function of Absolute Errors", pad=15, fontweight='bold')
    plt.xlabel("Absolute Error [m]")
    plt.ylabel("Cumulative Probability")
    plt.xlim(left=0)
    plt.grid(True, linestyle='-', alpha=0.6)
    plt.legend(loc='lower right')
    
    plt.tight_layout()
    save_format(output_filename, "Cumulative Distribution Function (CDF)")
    plt.close()


def process_space_domain(csv_path="data/benchmark_space_domain.csv"):
    """
    Orchestrates all space-domain plotting functions and precomputes 
    the absolute magnitude vectors.
    """
    if not os.path.exists(csv_path):
        print(f" [error] Space-domain data not found at: {csv_path}")
        return
        
    df = pd.read_csv(csv_path)
    df['SMA_km'] = df['SMA_m'] / 1000.0
    
    df['Abs_Radial_m'] = np.abs(df['Radial_m'])
    df['Abs_InTrack_m'] = np.abs(df['InTrack_m'])
    df['Abs_CrossTrack_m'] = np.abs(df['CrossTrack_m'])
    
    prefix = "figures/plot_space_domain"
    
    plot_space_domain_distributions(df, prefix)
    plot_space_domain_scatter_trends(df, prefix)
    plot_domain_heatmap(df, f"{prefix}_heatmap.png")
    plot_regime_violin(df, f"{prefix}_violin.png")
    plot_error_cdf(df, f"{prefix}_cdf.png")


