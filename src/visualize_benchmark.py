def configure_style():
    """
    Configures Matplotlib and Seaborn for high-quality figures.
    Uses default system fonts to prevent missing font warnings.
    """
    sns.set_theme(style="ticks")

    # Sizes and PDF export settings
    mpl.rcParams["axes.titlesize"] = 14
    mpl.rcParams["axes.labelsize"] = 12
    mpl.rcParams["xtick.labelsize"] = 11
    mpl.rcParams["ytick.labelsize"] = 11
    mpl.rcParams["legend.fontsize"] = 11
    mpl.rcParams["figure.titlesize"] = 16
    mpl.rcParams["figure.dpi"] = 300
    mpl.rcParams["pdf.fonttype"] = 42
    mpl.rcParams["ps.fonttype"] = 42


def save_format(output_path, description, bbox_inches="tight"):
    """
    Helper function to save the current figure in both PNG and SVG formats,
    and output a single clean, descriptive console notification.

    Args:
        output_path (str): Original target path (expected to end in .png).
        description (str): Human-readable description of the saved figure.
        bbox_inches (str): Bounding box specification for Matplotlib.
    """
    plt.savefig(output_path, dpi=300, bbox_inches=bbox_inches)
    vector_path = os.path.splitext(output_path)[0] + ".svg"
    plt.savefig(vector_path, bbox_inches=bbox_inches)

    print(f" [saved] {description}")


